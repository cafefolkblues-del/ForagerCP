namespace ForagerCP
{
    /// 저장에 자기 몫을 내놓는 것.
    ///
    /// 세이브가 각 시스템의 속을 들여다보지 않는다. 시스템이 자기 데이터를 스스로 꾸려 내놓고
    /// 돌려받는다 — 그래야 제작·방어구·보관함이 들어올 때 세이브 쪽을 다시 열 일이 없다.
    ///
    /// 묶음을 문자열(JSON)로 주고받는 이유: 시스템마다 저장할 모양이 다른데, 공통 타입을 만들면
    /// 새 시스템이 생길 때마다 그 타입을 고쳐야 한다. 각자 자기 모양을 알아서 접었다 펴게 둔다.
    public interface ISaveable
    {
        /// 저장 파일 안에서의 자리 이름. 한 번 정하면 바꾸지 않는다 — 바꾸면 옛 저장이 그 칸을 잃는다.
        string SaveKey { get; }

        /// 지금 상태를 JSON으로. 바뀐 게 없으면 매번 같은 문자열이 나와야 한다
        /// (서비스가 이 값을 직전과 비교해 '저장할 게 생겼는지'를 판단한다).
        string Capture();

        /// 저장에서 돌려받기. 저장 파일에 이 칸이 없으면 아예 불리지 않는다.
        void Restore(string payload);
    }

    /// 되돌리기 어려운 일이 일어났다고 알리는 것. 구현하지 않아도 된다.
    ///
    /// 광물을 캐거나 인벤 숫자가 바뀌는 잔 변화는 여기 해당하지 않는다 — 그런 것까지 신호로 삼으면
    /// 한 번 채집할 때마다 디스크를 때리고, 어차피 광물은 시간이 지나면 되살아난다.
    /// 보스 처치, 열쇠 획득, 구역 개방, 거래처럼 '꺼졌을 때 잃으면 곤란한' 일만 알린다.
    ///
    /// 자동으로 알아채지 않고 시스템이 직접 선언하게 둔 이유: 무엇이 큰 사건인지는 기획 판단이라
    /// 코드가 짐작하면 안 된다. 새 시스템은 필요할 때 이 인터페이스를 구현하면 된다.
    public interface ISaveMilestone
    {
        /// 인자는 사람이 읽을 사유(로그용).
        event System.Action<string> Milestone;
    }

    /// 슬롯 목록에 한 줄로 뭘 보여줄지. 구현하지 않아도 된다.
    public interface ISaveSummary
    {
        string Describe();
    }
}
